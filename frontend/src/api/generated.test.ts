import { describe, expect, it } from "vitest";

import generatedSource from "./generated.ts?raw";
import { READINESS_PATH } from "./readiness";

const OPENAPI_TYPESCRIPT_BANNER = "This file was auto-generated by openapi-typescript.";

/**
 * Guards the OpenAPI generation discipline (UI-F01 §14).
 *
 * `src/api/generated.ts` is a committed build artifact: it must be the output of the
 * generator, and it must reflect the backend the frontend actually talks to. Byte-level
 * drift against a fresh regeneration is `npm run check:api-drift`.
 */
describe("generated OpenAPI artifact", () => {
  it("is generator output rather than a hand-written authority DTO", () => {
    expect(generatedSource).toContain(OPENAPI_TYPESCRIPT_BANNER);
    expect(generatedSource).toContain("export interface paths");
  });

  it("includes the current runtime surfaces the frontend depends on", () => {
    expect(generatedSource).toContain('"/api/v1/live"');
    expect(generatedSource).toContain(`"${READINESS_PATH}"`);
  });

  it("includes the authenticated and public read surfaces used by UI V1", () => {
    for (const path of ["/api/v1/auth/login", "/api/v1/health", "/api/v1/runtime"]) {
      expect(generatedSource).toContain(`"${path}"`);
    }
  });
});
